            <h4 id="choosing-strain-heading">
                So, How Do I Choose?
            </h4>

            <p>
                Instead of asking only
                <strong>"indica or sativa?"</strong>,
                ask a few questions about the actual
                product. You don't need to become a
                cannabis scientist. You just need better
                information than a strain name alone.
            </p>

            <ol class="strain-steps">

                <li>
                    <strong>Start with the Product Type:</strong>
                    Decide whether you're looking at flower,
                    an edible, a concentrate, an oil, or
                    something else. The method of use
                    matters.
                </li>

                <li>
                    <strong>Check the THC:</strong>
                    Higher THC can mean stronger
                    intoxicating effects and a greater
                    chance of having more than you
                    intended.
                </li>

                <li>
                    <strong>Check the CBD:</strong>
                    Look at whether the product is
                    THC-dominant, CBD-dominant, or contains
                    meaningful amounts of both.
                </li>

                <li>
                    <strong>Look at the Terpenes:</strong>
                    If a terpene profile is available, use
                    it to understand more about the
                    product's aroma and chemistry, not as
                    a guaranteed effects chart.
                </li>

                <li>
                    <strong>Check the Actual Batch:</strong>
                    The same strain from another grower or
                    harvest may not be exactly the same
                    product.
                </li>

                <li>
                    <strong>Consider Your Experience:</strong>
                    Someone else's favorite strain isn't
                    automatically going to be yours.
                </li>

                <li>
                    <strong>Don't Chase THC Alone:</strong>
                    The highest number on the menu isn't
                    automatically the highest-quality or
                    best-fitting product.
                </li>

                <li>
                    <strong>Remember What Worked:</strong>
                    If you're trying to understand your own
                    preferences, remember the product,
                    cannabinoid information, amount used,
                    method of use, and how you responded.
                    That's more useful than remembering
                    only "I liked an indica once."
                </li>

            </ol>

        </article>


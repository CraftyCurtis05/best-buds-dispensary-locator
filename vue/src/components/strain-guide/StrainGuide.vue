            <h4 id="strain-questions-heading">
                Quick Questions
            </h4>

            <dl>

                <dt>
                    Does indica always make you sleepy?
                </dt>

                <dd>
                    No. Indica products are commonly
                    marketed as relaxing or sleepy, but the
                    label doesn't guarantee those effects.
                </dd>

                <dt>
                    Does sativa always give you energy?
                </dt>

                <dd>
                    No. Sativa is commonly marketed as
                    uplifting or energizing, but product
                    chemistry and individual responses can
                    vary.
                </dd>

                <dt>
                    Is hybrid always a balance of both?
                </dt>

                <dd>
                    No. Hybrid is a very broad category. It
                    doesn't automatically mean equal parts
                    "indica effects" and "sativa effects."
                </dd>

                <dt>
                    Are strain names reliable?
                </dt>

                <dd>
                    They're useful for identifying and
                    talking about products, but they're not
                    standardized chemical recipes. Products
                    sharing a strain name can vary between
                    growers and batches.
                </dd>

                <dt>
                    Is "strain" or "cultivar" the right word?
                </dt>

                <dd>
                    You'll hear both. "Strain" is extremely
                    common in cannabis culture and retail,
                    while "cultivar" is a more plant-focused
                    term for a cultivated variety. For most
                    people shopping for cannabis, knowing
                    what the actual product contains matters
                    more than debating the terminology.
                </dd>

                <dt>
                    What matters more than the strain name?
                </dt>

                <dd>
                    THC and CBD, product type, potency,
                    amount used, available terpene
                    information, the actual batch, your
                    previous experience, and individual
                    differences can all matter.
                </dd>

                <dt>
                    Does more THC mean better cannabis?
                </dt>

                <dd>
                    No. THC concentration tells you
                    something about potency, not overall
                    quality. Higher THC can produce stronger
                    intoxicating effects and increase the
                    chance of overconsumption.

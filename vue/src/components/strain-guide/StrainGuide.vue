            <h4 id="strain-labels-heading">
                Indica, Sativa & Hybrid
            </h4>

            <p>
                Indica, sativa, and hybrid are probably the
                three cannabis labels you'll see most
                often. They're useful for understanding how
                a product is being categorized or marketed,
                but they shouldn't be treated like three
                guaranteed sets of effects.
            </p>

            <p>
                Modern cannabis has been heavily bred and
                crossbred. Research comparing commercial
                cannabis has found that indica and sativa
                labels don't neatly separate products into
                distinct overall genetic or chemical groups.
            </p>

            <p>
                That doesn't make the labels useless. It
                just means they work better as
                <strong>general categories</strong>
                than as instructions for how you're going
                to feel.
            </p>


            <h4 id="finding-preferences-heading">
                Finding What Works for You
            </h4>

            <p>
                Cannabis can be surprisingly personal.
                Two people can use the same product and
                describe it very differently. Even your
                own response can change depending on the
                amount, setting, tolerance, other
                substances, or how you're feeling that day.
            </p>

            <p>
                If you find a product you like, pay
                attention to more than its name. Look at
                the cannabinoid profile, product type,
                potency, available terpene information,
                grower or brand, and batch when possible.
            </p>

            <p>
                Over time, that can help you recognize
                patterns in the products you prefer without
                assuming every indica, sativa, hybrid, or
                strain name will behave the same way.
            </p>


            <h4 id="understanding-strains-heading">
                What Actually Makes Cannabis Different?
            </h4>

            <p>
                Two products with different strain names can
                have similar chemistry, while two products
                with the same name can be surprisingly
                different. That's why the information on
                the product you're actually considering can
                be more useful than the name printed on the
                package.
            </p>

            <h5>
                Look Beyond the Name
            </h5>

            <ul class="strain-details">

                <li>
                    <strong>THC:</strong>
                    The main intoxicating cannabinoid in
                    cannabis. Higher THC can mean stronger
                    intoxicating effects and a greater
                    chance of using more THC than you
                    intended. More THC doesn't automatically
                    mean better cannabis.
                </li>

                <li>
                    <strong>CBD:</strong>
                    CBD doesn't produce the same THC-like
                    high. Products can contain very
                    different amounts and ratios of THC
                    and CBD.
                </li>

                <li>
                    <strong>Other Cannabinoids:</strong>
                    Cannabis contains many cannabinoids
                    beyond THC and CBD. You may see names
                    such as CBG, CBC, CBN, THCV, and others.
                    Research into many of these compounds
                    and their effects is still developing.
                </li>

                <li>
                    <strong>Terpenes:</strong>
                    These aromatic compounds help create
                    cannabis's smell and flavor. You may see
                    names like myrcene, limonene, pinene,
                    linalool, and caryophyllene on product
                    information.
                </li>

                <li>
                    <strong>Potency:</strong>
                    Look at the actual cannabinoid
                    information instead of assuming one
                    strain name is stronger than another.
                </li>

                <li>
                    <strong>Product Type:</strong>
                    Flower, concentrates, edibles, oils,
                    and other cannabis products aren't
                    interchangeable. How cannabis enters
                    your body can change how quickly effects
                    begin, how intense they feel, and how
                    long they last.
                </li>

                <li>
                    <strong>Amount Used:</strong>
                    The same product can feel very different
                    depending on how much you use.
                </li>

                <li>
                    <strong>Batch and Grower:</strong>
                    Growing conditions, genetics,
                    harvesting, processing, and storage can
                    contribute to differences between
                    products carrying the same strain name.
                </li>

                <li>
                    <strong>Your Own Experience:</strong>
                    Previous cannabis use, tolerance,
                    biology, medications, other substances,
                    setting, and individual differences can
                    all affect how cannabis feels.
                </li>

            </ul>

        </article>


                Cultivar is a plant-focused term for a
                cultivated variety. In everyday cannabis
                shopping, people commonly use "strain" even
                when "cultivar" may be the more precise
                horticultural term.
            </p>

            <p>
                The important thing isn't which word you
                choose. It's understanding that a strain
                name isn't a standardized recipe. Cannabis
                sold under the same name can vary between
                growers, harvests, and batches.
            </p>


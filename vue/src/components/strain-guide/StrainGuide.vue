            <h4 id="reading-cannabis-heading">
                Learn to Read the Product
            </h4>

            <p>
                The strain name can be useful, but the
                package in your hand tells you about the
                product you actually have. When that
                information is available, use it.
            </p>

            <h5>
                What to Compare
            </h5>

            <ul class="strain-details">

                <li>
                    <strong>THC and THCA:</strong>
                    Flower can contain both THC and THCA.
                    THCA can convert into intoxicating THC
                    when cannabis is heated, so don't judge
                    potential potency from one number
                    without understanding the label.
                </li>

                <li>
                    <strong>CBD:</strong>
                    Check whether CBD is present and how
                    its amount compares with THC.
                </li>

                <li>
                    <strong>Total THC:</strong>
                    Some regulated cannabis labels provide
                    total THC information that accounts for
                    THC and the potential contribution of
                    THCA.
                </li>

                <li>
                    <strong>Terpenes:</strong>
                    These can help describe aroma and
                    chemical differences between products,
                    but don't treat them like guaranteed
                    mood settings.
                </li>

                <li>
                    <strong>Product Type:</strong>
                    A strain name on flower doesn't mean an
                    edible or concentrate carrying the same
                    name will provide an identical
                    experience.
                </li>

                <li>
                    <strong>Batch Information:</strong>
                    When available, batch-specific
                    cannabinoid and testing information is
                    more directly connected to the product
                    you're buying than a general online
                    strain description.
                </li>

            </ul>

        </article>


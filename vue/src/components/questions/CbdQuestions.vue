                    isolate?
                </h4>

                <ul class="answer-list">

                    <li>
                        <strong>Full-Spectrum:</strong>
                        Usually describes a hemp or cannabis
                        extract containing CBD along with
                        other cannabinoids and plant
                        compounds. It may contain THC.
                    </li>

                    <li>
                        <strong>Broad-Spectrum:</strong>
                        Usually describes an extract
                        containing CBD and other plant
                        compounds with THC removed or
                        reduced.
                    </li>

                    <li>
                        <strong>CBD Isolate:</strong>
                        CBD that has been separated from most
                        other cannabinoids and plant
                        compounds.
                    </li>

                    <li>
                        These are common industry terms, but
                        don't rely on the name alone to
                        guarantee exactly what's in the
                        product.
                    </li>

                    <li>
                        Check the cannabinoid information and
                        available testing when knowing the
                        actual contents matters.
                    </li>

                </ul>

            </li>


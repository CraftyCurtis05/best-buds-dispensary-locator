            <li>

                <h4>
                    What is CBD?
                </h4>

                <ul class="answer-list">

                    <li>
                        CBD, or cannabidiol, is one of the
                        cannabinoids naturally found in
                        cannabis.
                    </li>

                    <li>
                        CBD can come from hemp or marijuana.
                        The CBD molecule itself isn't
                        different just because it came from
                        one legal category of cannabis or
                        the other.
                    </li>

                    <li>
                        CBD doesn't produce the same
                        intoxicating high associated with
                        THC.
                    </li>

                    <li>
                        That doesn't mean CBD has no effects
                        on the body or that every CBD
                        product is harmless.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    What's the difference between CBD and
                    THC?
                </h4>

                <ul class="answer-list">

                    <li>
                        <strong>THC:</strong>
                        Delta-9-tetrahydrocannabinol is the
                        primary cannabinoid responsible for
                        the cannabis high.
                    </li>

                    <li>
                        <strong>CBD:</strong>
                        Cannabidiol doesn't produce that same
                        intoxicating high.
                    </li>

                    <li>
                        Both are biologically active
                        cannabinoids, and both are being
                        studied for different effects and
                        possible medical uses.
                    </li>

                    <li>
                        A product marketed as CBD may also
                        contain THC or other cannabinoids,
                        so read more than the big letters on
                        the front of the package.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can CBD get me high?
                </h4>

                <ul class="answer-list">

                    <li>
                        CBD itself doesn't produce the same
                        intoxicating high as THC.
                    </li>

                    <li>
                        But not every product labeled "CBD"
                        contains only CBD.
                    </li>

                    <li>
                        Full-spectrum products can contain
                        THC, and product labeling isn't
                        always perfect.
                    </li>

                    <li>
                        If avoiding THC matters to you, check
                        the ingredient list, cannabinoid
                        information, and available product
                        testing instead of assuming the word
                        "CBD" means THC-free.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Does "non-intoxicating" mean CBD doesn't
                    affect me?
                </h4>

                <ul class="answer-list">

                    <li>
                        No. Non-intoxicating means CBD
                        doesn't produce the typical THC high.
                    </li>

                    <li>
                        CBD can still affect the body, cause
                        side effects, interact with
                        medications, or make some people
                        sleepy.
                    </li>

                    <li>
                        That's why "non-intoxicating" is more
                        useful than treating CBD as if it
                        does nothing at all.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Is CBD completely safe?
                </h4>

                <ul class="answer-list">

                    <li>
                        No. "Non-intoxicating" and
                        "risk-free" aren't the same thing.
                    </li>

                    <li>
                        CBD can cause side effects, interact
                        with medications, and can cause liver
                        injury.
                    </li>

                    <li>
                        There are also unanswered questions
                        about long-term use, different
                        amounts, and how CBD affects certain
                        groups of people.
                    </li>

                    <li>
                        Product quality matters too. A CBD
                        product may contain a different
                        amount of CBD than the label claims
                        or may contain THC or contaminants.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    What side effects can CBD cause?
                </h4>

                <ul class="answer-list">

                    <li>
                        Possible side effects can include
                        sleepiness or changes in alertness.
                    </li>

                    <li>
                        CBD can also cause diarrhea,
                        decreased appetite, stomach
                        discomfort, or changes in mood such
                        as irritability or agitation.
                    </li>

                    <li>
                        CBD can cause liver injury, including
                        changes in liver enzymes that may require
                        medical monitoring in some situations.
                    </li>

                    <li>
                        The risks can depend on the amount,
                        frequency, other medications or
                        substances, and the individual.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can CBD interact with medications?
                </h4>

                <ul class="answer-list">

                    <li>
                        Yes. CBD can change how some
                        medications work and can increase
                        the risk of side effects.
                    </li>

                    <li>
                        Combining CBD with alcohol or
                        medications and substances that cause
                        sleepiness can increase sedation and
                        drowsiness.
                    </li>

                    <li>
                        If you regularly take prescription
                        medications, over-the-counter
                        medications, or supplements, talk
                        with a healthcare professional or
                        pharmacist before adding CBD.
                    </li>

                    <li>
                        This is especially important if the
                        medication already has warnings
                        about drowsiness, liver effects, or
                        interactions with other drugs.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Is CBD proven to help pain, anxiety, or
                    sleep?
                </h4>

                <ul class="answer-list">

                    <li>
                        CBD is being studied for many
                        possible uses, including pain,
                        anxiety, sleep, and other health
                        concerns.
                    </li>

                    <li>
                        But research being promising isn't
                        the same thing as a treatment being
                        proven safe and effective.
                    </li>

                    <li>
                        Ordinary CBD gummies, oils, drinks,
                        creams, and other consumer products
                        aren't FDA-approved treatments for
                        pain, anxiety, or sleep disorders.
                    </li>

                    <li>
                        Be cautious when a product promises
                        to diagnose, treat, cure, or prevent
                        a medical condition.
                    </li>

                </ul>


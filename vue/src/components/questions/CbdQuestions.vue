                    Is any CBD medicine actually
                    FDA-approved?
                </h4>

                <ul class="answer-list">

                    <li>
                        Yes. The FDA has approved Epidiolex,
                        a prescription medication containing
                        purified CBD.
                    </li>

                    <li>
                        It is approved for seizures associated
                        with Lennox-Gastaut syndrome, Dravet
                        syndrome, and tuberous sclerosis
                        complex in patients 1 year of age
                        and older.
                    </li>

                    <li>
                        That approval applies to that
                        specific prescription medication —
                        not every CBD oil, gummy, drink,
                        cream, or other consumer product.
                    </li>

                    <li>
                        A store selling CBD doesn't make its
                        products equivalent to an
                        FDA-approved prescription medicine.
                    </li>

                </ul>

            </li>


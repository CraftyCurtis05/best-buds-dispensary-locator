                <h4>
                    What should I look for on a CBD label?
                </h4>

                <ul class="answer-list">

                    <li>
                        Look for the amount of CBD in the
                        entire product and, when applicable,
                        the amount in each serving.
                    </li>

                    <li>
                        Check whether THC or other
                        cannabinoids are listed.
                    </li>

                    <li>

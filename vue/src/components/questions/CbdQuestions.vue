                    How much CBD should I take?
                </h4>

                <ul class="answer-list">

                    <li>
                        There isn't one universal CBD amount
                        that has been established as safe and
                        appropriate for everyone.
                    </li>

                    <li>
                        Product type, CBD concentration,
                        medications, health conditions,
                        frequency of use, and individual
                        differences can all matter.
                    </li>

                    <li>
                        Read the actual amount of CBD on the
                        label rather than guessing from terms
                        like "extra strength" or "maximum
                        strength."
                    </li>

                    <li>
                        More CBD isn't automatically more
                        useful.
                    </li>

                    <li>
                        If you're using CBD for a health
                        concern or take medications, a
                        healthcare professional can help
                        with questions specific to you.
                    </li>


                        milliliter, and milligrams in the
                        entire bottle don't mean the same
                        thing.
                    </li>

                    <li>
                        Look at the serving information,
                        ingredients, allergens, warnings,
                        expiration or freshness information,
                        and directions for use.
                    </li>

                    <li>
                        When trustworthy product testing is
                        available, compare the test results
                        with what the product claims on its
                        label.
                    </li>

                    <li>
                        Be cautious with products that
                        promise to cure diseases or make
                        dramatic medical claims.
                    </li>

                </ul>


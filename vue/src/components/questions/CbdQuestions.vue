                    Is CBD legal everywhere in the United
                    States?
                </h4>

                <ul class="answer-list">

                    <li>
                        No. CBD law is more complicated than
                        "hemp is legal, so CBD is legal."
                    </li>

                    <li>
                        Federal hemp law, FDA rules, state
                        cannabis and hemp laws, product type,
                        THC content, and how a product is
                        made or sold can all matter.
                    </li>

                    <li>
                        States can place their own
                        restrictions on CBD and hemp-derived
                        products, including rules for food,
                        beverages, age, labeling, testing,
                        cannabinoids, and retail sales.
                    </li>

                    <li>
                        A product being sold online or in a
                        store doesn't automatically prove
                        that every way it is marketed or
                        sold complies with federal and state
                        law.
                    </li>

                    <li>
                        Check our

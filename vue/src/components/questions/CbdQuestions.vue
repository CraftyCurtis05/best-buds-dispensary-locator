                <h4>
                    What is a Certificate of Analysis?
                </h4>

                <ul class="answer-list">

                    <li>
                        A Certificate of Analysis, often
                        called a COA, is a laboratory report
                        showing information about a tested
                        product.
                    </li>

                    <li>
                        Depending on the testing, it may show
                        CBD, THC, and other cannabinoid
                        levels and results for certain
                        contaminants.
                    </li>

                    <li>
                        Make sure the report actually matches
                        the product and batch you're holding.
                        A random lab report for a different
                        product isn't very helpful.
                    </li>

                    <li>
                        Look for a batch or lot number and
                        compare it with the number on the
                        product when that information is
                        available.
                    </li>

                    <li>
                        A COA can provide useful information,
                        but it doesn't automatically prove
                        that every claim a company makes
                        about the product is true.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can a CBD product contain THC even if I
                    don't expect it to?
                </h4>

                <ul class="answer-list">

                    <li>
                        Yes. Some CBD products intentionally
                        contain THC, while others may contain
                        THC because of the extract used,
                        manufacturing differences, or
                        inaccurate labeling.
                    </li>

                    <li>
                        Full-spectrum products may contain
                        THC even when CBD is the main
                        cannabinoid being advertised.
                    </li>

                    <li>
                        FDA has raised concerns about
                        consumer CBD products not always
                        containing the cannabinoid amounts
                        they claim and about possible
                        contaminants.
                    </li>

                    <li>
                        If avoiding THC is important, don't
                        rely only on terms such as "CBD,"
                        "hemp," or "broad-spectrum."
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can CBD make me fail a drug test?
                </h4>

                <ul class="answer-list">

                    <li>
                        It's possible when a CBD product also
                        exposes you to THC.
                    </li>

                    <li>
                        Full-spectrum products can contain
                        THC, and even products marketed as
                        THC-free may not always match their
                        labels perfectly.
                    </li>

                    <li>
                        If you're subject to drug testing,
                        don't assume a CBD label guarantees
                        that a product can't affect your
                        test result.
                    </li>

                    <li>
                        A product being legal to purchase
                        also doesn't guarantee that an
                        employer, sports organization, or
                        other testing program will treat it
                        differently.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can I drive after taking CBD?
                </h4>

                <ul class="answer-list">

                    <li>
                        Don't drive if CBD makes you sleepy,
                        less alert, dizzy, or otherwise
                        affected.
                    </li>

                    <li>
                        CBD can cause drowsiness, and
                        combining it with alcohol or other
                        substances that cause sedation can
                        make that worse.
                    </li>

                    <li>
                        A product sold as CBD may also
                        contain THC, which can impair
                        driving.
                    </li>

                    <li>
                        The fact that CBD itself doesn't
                        produce the usual THC high isn't a
                        reason to ignore how you actually
                        feel.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can I use CBD during pregnancy or while
                    breastfeeding?
                </h4>

                <ul class="answer-list">

                    <li>
                        FDA strongly advises against using
                        CBD, THC, or marijuana in any form
                        during pregnancy or while
                        breastfeeding.
                    </li>

                    <li>
                        The effects of CBD exposure during
                        pregnancy are not fully understood,
                        and important safety questions remain.
                    </li>

                    <li>
                        Some CBD is expected to pass into
                        breast milk. How much transfers and
                        what effects that exposure may have on
                        a breastfed baby are not well
                        understood.
                    </li>

                    <li>
                        Consumer CBD products can have
                        additional concerns involving
                        labeling, unexpected THC, ingredients,
                        and contaminants.
                    </li>

                    <li>
                        Talk with a healthcare professional
                        about safer options for symptoms
                        you're trying to manage.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can children use CBD?
                </h4>

                <ul class="answer-list">

                    <li>
                        Don't assume a consumer CBD product
                        is safe for children because it's
                        marketed as natural or
                        non-intoxicating.
                    </li>

                    <li>
                        Epidiolex, the FDA-approved prescription
                        CBD medication, can be prescribed for
                        certain seizure disorders in patients
                        1 year of age and older.
                    </li>

                    <li>
                        That approval does not mean ordinary
                        CBD gummies, oils, drinks, or other
                        consumer products have been proven safe
                        or effective for children.
                    </li>

                    <li>
                        CBD use in children should be
                        discussed with an appropriate
                        healthcare professional.
                    </li>

                    <li>
                        Keep CBD products securely stored
                        away from children, especially
                        gummies and other products that
                        resemble ordinary food or candy.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Is CBD safe for pets?
                </h4>

                <ul class="answer-list">

                    <li>
                        Don't assume that a CBD product is
                        safe or effective just because the
                        package has a dog or cat on it.
                    </li>

                    <li>
                        FDA has not approved CBD products for
                        use in animals and has raised safety
                        concerns about products marketed for
                        pets.
                    </li>

                    <li>
                        If you're considering CBD for a pet,
                        talk with a veterinarian about
                        appropriate treatment options.
                    </li>

                    <li>
                        Never give a pet a human cannabis
                        product without checking its other
                        ingredients. Products such as
                        chocolate edibles can contain
                        ingredients that are dangerous to
                        animals in addition to cannabinoids.
                    </li>

                    <li>
                        If a pet accidentally consumes a
                        cannabis or CBD product and seems
                        sick, contact a veterinarian, animal
                        emergency hospital, or animal poison
                        control service.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can CBD help with addiction recovery?
                </h4>

                <ul class="answer-list">

                    <li>
                        CBD is being researched for substance
                        use disorders, cravings, and other
                        possible uses.
                    </li>

                    <li>
                        But ordinary consumer CBD products
                        aren't FDA-approved treatments for
                        opioid use disorder or other
                        substance use disorders.
                    </li>

                    <li>
                        CBD shouldn't replace proven
                        treatment or medications prescribed
                        for a substance use disorder.
                    </li>

                    <li>
                        If you're looking for help with
                        substance use, talk with a qualified
                        healthcare professional rather than
                        relying on CBD marketing claims.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    How quickly does CBD work?
                </h4>

                <ul class="answer-list">

                    <li>
                        There isn't one reliable timing rule
                        for every CBD product.
                    </li>

                    <li>
                        How CBD is used can affect absorption
                        and timing. A swallowed product, a
                        product used in the mouth, an inhaled
                        product, and a topical product aren't
                        interchangeable.
                    </li>

                    <li>
                        The formulation, amount, whether
                        you've eaten, other medications, and
                        individual differences can also
                        matter.
                    </li>

                    <li>
                        Be cautious with products that
                        promise an exact onset time or
                        guaranteed effect for everyone.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Do CBD topicals work differently from
                    CBD you swallow?
                </h4>

                <ul class="answer-list">

                    <li>
                        Yes. A cream applied to the skin
                        isn't the same type of exposure as
                        swallowing CBD.
                    </li>

                    <li>
                        Questions remain about how much CBD
                        is absorbed through the skin from
                        different consumer products.
                    </li>

                    <li>
                        Traditional topicals and products
                        specifically designed for
                        transdermal delivery shouldn't
                        automatically be treated as the same
                        thing.
                    </li>

                    <li>
                        A topical can also contain other
                        active-feeling ingredients such as
                        menthol or camphor, so an effect
                        isn't necessarily proof that CBD
                        caused it.
                    </li>

                    <li>
                        Claims that a CBD cream is proven to
                        treat pain, arthritis, inflammation,
                        or a skin condition should be viewed
                        carefully.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Is vaping CBD safe?
                </h4>

                <ul class="answer-list">

                    <li>
                        Don't assume that vaping CBD is
                        harmless because CBD itself doesn't
                        produce the THC high.
                    </li>

                    <li>
                        Inhaling a vape product creates
                        different exposures and risks than
                        swallowing CBD or applying a topical.
                    </li>

                    <li>
                        Ingredients, contaminants, device
                        quality, and product source can all
                        matter.
                    </li>

                    <li>
                        An oral CBD tincture, topical oil,
                        cooking oil, or essential oil should
                        not be put into a vape.
                    </li>

                    <li>
                        Only products specifically
                        manufactured and labeled for
                        vaporization should be treated as
                        vape products.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Is hemp seed oil the same thing as CBD
                    oil?
                </h4>

                <ul class="answer-list">

                    <li>
                        No. Hemp seed oil and CBD oil aren't
                        interchangeable terms.
                    </li>

                    <li>
                        Hemp seed oil is made from hemp
                        seeds and is commonly used as a food
                        or cosmetic ingredient.
                    </li>

                    <li>
                        CBD is found mainly in other parts of
                        the cannabis plant and has to be
                        present in the product for it to be
                        a CBD product.
                    </li>

                    <li>
                        A bottle saying "hemp oil" on the
                        front doesn't automatically mean it
                        contains CBD.
                    </li>

                    <li>
                        Check the ingredient list and actual
                        cannabinoid amount instead of
                        assuming the terms mean the same
                        thing.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Does "natural" mean a CBD product is
                    safer?
                </h4>

                <ul class="answer-list">

                    <li>
                        No. "Natural" isn't a guarantee of
                        safety, quality, purity, or
                        effectiveness.
                    </li>

                    <li>
                        A plant-derived substance can still
                        cause side effects or interact with
                        medications.
                    </li>

                    <li>
                        Other ingredients in a CBD product
                        can also matter, including
                        sweeteners, flavorings, fragrances,
                        carrier oils, or other active
                        ingredients.
                    </li>

                    <li>
                        Look at what's actually in the
                        product instead of treating
                        "natural" as a safety rating.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    How should I store CBD?
                </h4>

                <ul class="answer-list">

                    <li>
                        Follow the storage directions on the
                        specific product.
                    </li>

                    <li>
                        Keep CBD securely stored away from
                        children and pets.
                    </li>

                    <li>
                        Gummies, chocolates, drinks, and
                        other edible-looking products deserve
                        extra attention because they can be
                        mistaken for ordinary food.
                    </li>

                    <li>
                        Keeping products in their original,
                        clearly labeled packaging can help
                        prevent mix-ups.
                    </li>

                    <li>
                        Heat, light, air, and moisture can
                        affect some products, so don't assume
                        every type of CBD should be stored
                        the same way.
                    </li>

                </ul>

            </li>


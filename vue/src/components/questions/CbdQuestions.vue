                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Is CBD considered a dietary supplement
                    by the FDA?
                </h4>

                <ul class="answer-list">

                    <li>
                        No. Under FDA's current position,
                        products containing CBD can't simply
                        be marketed as dietary supplements
                        under federal food and drug law.
                    </li>

                    <li>
                        The fact that CBD came from hemp
                        doesn't remove FDA's authority over
                        foods, drugs, cosmetics, and other

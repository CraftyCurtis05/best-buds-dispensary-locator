                            But an ordinary cannabis or CBD
                            tincture shouldn't automatically
                            be described as proven to treat
                            pain, anxiety, insomnia,
                            inflammation, nausea, cancer, or
                            another medical condition.
                        </li>

                        <li>
                            The FDA has not approved cannabis
                            itself as a treatment for a
                            disease or condition.
                        </li>

                        <li>
                            Specific prescription
                            cannabinoid medications have been
                            FDA-approved for particular uses.
                            That's different from approval of
                            ordinary retail or dispensary
                            tinctures.
                        </li>

                        <li>
                            Be cautious with tinctures
                            promising to cure, prevent, or
                            treat diseases.
                        </li>


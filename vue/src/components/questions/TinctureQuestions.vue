                <li>

                    <h5>
                        Can a tincture get me high?
                    </h5>

                    <ul class="answer-list">

                        <li>
                            Yes, if it contains enough THC or
                            another intoxicating cannabinoid.
                        </li>

                        <li>
                            CBD doesn't produce the same
                            intoxicating high as THC.
                        </li>

                        <li>
                            Don't assume a tincture is
                            non-intoxicating just because it's
                            liquid, sold in a small bottle, or
                            marketed around CBD.
                        </li>

                        <li>
                            Check the actual cannabinoid
                            contents.
                        </li>

                    </ul>

                </li>

                <li>

                    <h5>
                        What unwanted effects can THC
                        tinctures cause?
                    </h5>

                    <ul class="answer-list">

                        <li>
                            THC can cause anxiety, panic,
                            paranoia, confusion, dizziness,
                            changes in perception, impaired
                            coordination, increased heart
                            rate, nausea, and other unwanted
                            effects.
                        </li>

                        <li>
                            Greater THC exposure can increase
                            the chance that an experience
                            becomes uncomfortable.
                        </li>

                        <li>
                            Oral THC can also be easier to
                            overconsume when someone takes
                            more before the first amount has
                            fully affected them.
                        </li>

                    </ul>

                </li>

                <li>

                    <h5>
                        What should I do if I take too much
                        THC tincture?
                    </h5>

                    <ul class="answer-list">

                        <li>
                            Stop using more cannabis.
                        </li>

                        <li>
                            Get somewhere safe and don't
                            drive.
                        </li>

                        <li>
                            If possible, have a trusted sober
                            person stay nearby.
                        </li>

                        <li>
                            Keep things calm and give the
                            effects time to wear off.
                        </li>

                        <li>
                            Don't add alcohol or other drugs
                            in an attempt to change the
                            experience.
                        </li>

                        <li>
                            Don't rely on coffee, food, CBD,
                            peppercorns, a shower, or another
                            home remedy as an instant THC
                            antidote.
                        </li>

                        <li>
                            In the United States, Poison
                            Control can be reached at
                            <strong>1-800-222-1222</strong>
                            if you're concerned or unsure
                            what to do.
                        </li>

                        <li>
                            Call 911 for an emergency,
                            including trouble breathing,
                            seizure, loss of consciousness,
                            serious injury, or another
                            life-threatening situation.
                        </li>

                    </ul>

                </li>

                <li>

                    <h5>
                        Is CBD tincture completely safe
                        because it doesn't cause a THC-like
                        high?
                    </h5>

                    <ul class="answer-list">

                        <li>
                            No. Non-intoxicating doesn't mean
                            risk-free.
                        </li>

                        <li>
                            CBD can cause side effects,
                            including drowsiness and
                            gastrointestinal symptoms.
                        </li>

                        <li>
                            CBD can interact with medications
                            and has been associated with
                            potential liver injury.
                        </li>

                        <li>
                            Consumer CBD products can also
                            vary in quality and may not always
                            contain exactly what someone
                            expects from the label.
                        </li>

                    </ul>

                </li>

                <li>

                    <h5>
                        Can tinctures interact with
                        medications?
                    </h5>

                    <ul class="answer-list">

                        <li>
                            Yes. Cannabis-derived compounds
                            can interact with medications.
                        </li>

                        <li>
                            CBD in particular can affect how
                            some medications work, and other
                            medications can affect CBD too.
                        </li>

                        <li>
                            Combining cannabis products with
                            medications or substances that
                            cause drowsiness can also increase
                            sedation.
                        </li>

                        <li>
                            If you take prescription
                            medications, ask a healthcare
                            professional or pharmacist about
                            possible interactions.
                        </li>

                    </ul>

                </li>

                <li>

                    <h5>
                        Can I mix a tincture with alcohol?
                    </h5>

                    <ul class="answer-list">

                        <li>
                            Be careful about combining
                            cannabis with alcohol.
                        </li>

                        <li>
                            Cannabis and alcohol together can
                            increase impairment.
                        </li>

                        <li>
                            CBD can also cause drowsiness, and
                            combining CBD with alcohol or
                            other substances that slow brain
                            activity can increase sedation
                            and sleepiness.
                        </li>

                        <li>
                            Don't use alcohol as a way to try
                            to change or cancel an
                            uncomfortable cannabis
                            experience.
                        </li>

                    </ul>

                </li>


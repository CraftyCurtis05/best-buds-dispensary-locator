                            Sublingual generally means under
                            the tongue.
                        </li>

                        <li>
                            Some tinctures are designed to
                            spend time in the mouth before
                            being swallowed.
                        </li>

                        <li>
                            The idea is that some compounds
                            may be absorbed through tissues in
                            the mouth while the rest is
                            swallowed.
                        </li>

                        <li>
                            Exactly how much is absorbed in
                            the mouth can vary with the
                            product and how it's used.
                        </li>

                        <li>
                            "Sublingual" shouldn't be treated
                            as a guarantee of one exact onset
                            time.
                        </li>

                    </ul>

                </li>


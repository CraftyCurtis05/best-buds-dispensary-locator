                            under-the-tongue rule that applies
                            to every product.
                        </li>

                        <li>
                            Formulations differ, and products
                            may give different directions for
                            use.
                        </li>

                        <li>
                            Follow the instructions for your
                            specific tincture rather than
                            treating a certain number of
                            seconds as a rule for every
                            bottle.
                        </li>

                        <li>
                            If a THC-containing product is
                            swallowed, part of the experience
                            can behave more like other
                            swallowed cannabis products.

                        or condition.
                    </li>

                    <li>
                        The FDA has approved one
                        cannabis-derived prescription drug
                        containing purified CBD and several
                        synthetic cannabis-related
                        prescription drugs for specific
                        medical uses.
                    </li>

                    <li>
                        Those approvals don't apply to
                        ordinary cannabis products sold at
                        dispensaries or CBD products sold in
                        stores or online.
                    </li>

                    <li>
                        If you're considering cannabis for a
                        medical condition, especially while
                        taking other medications, talk with
                        a qualified healthcare professional.
                    </li>

                </ul>


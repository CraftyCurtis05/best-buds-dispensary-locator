                        cannabinoids, terpenes, and other
                        cannabis compounds may interact and
                        change the overall effects of a
                        product.
                    </li>

                    <li>
                        It's an interesting area of research,
                        but a predictable entourage effect
                        hasn't been established well enough
                        in humans to guarantee what a
                        particular combination will do.
                    </li>

                    <li>
                        Be skeptical of products that use the
                        phrase as proof that they will create
                        a specific feeling or health benefit.
                    </li>


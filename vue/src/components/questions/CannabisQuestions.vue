                    sleep problems?
                </h4>

                <ul class="answer-list">

                    <li>
                        CBD is being researched for many
                        possible uses, but products sold in
                        stores or online shouldn't be
                        assumed to be proven treatments for
                        pain, anxiety, sleep problems, or
                        other medical conditions.
                    </li>

                    <li>
                        The FDA has approved a purified CBD
                        prescription medication for specific
                        seizure disorders.
                    </li>

                    <li>
                        That approval doesn't apply to
                        ordinary CBD oils, gummies, creams,
                        drinks, or other consumer products.
                    </li>

                    <li>
                        CBD can also cause side effects and
                        interact with medications.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can cannabis interact with medications?
                </h4>

                <ul class="answer-list">

                    <li>
                        Yes. Cannabis and cannabinoids can
                        interact with some medications or
                        affect their side effects.
                    </li>

                    <li>
                        CBD in particular can affect how
                        certain medications work, and
                        combining substances that cause
                        drowsiness may increase sedation.
                    </li>

                    <li>
                        If you take prescription
                        medications, over-the-counter
                        medications, supplements, or other
                        substances regularly, talk with a
                        healthcare professional or
                        pharmacist about possible
                        interactions.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    What happens if I mix cannabis and
                    alcohol?
                </h4>

                <ul class="answer-list">

                    <li>
                        Using alcohol and cannabis together
                        can cause greater impairment than
                        using either one alone.
                    </li>

                    <li>
                        That can increase problems with
                        coordination, judgment, reaction
                        time, and decision-making.
                    </li>

                    <li>
                        Mixing them can also make it harder
                        to judge how impaired you actually
                        are.
                    </li>

                    <li>
                        Adding more substances doesn't make
                        an uncomfortable cannabis experience
                        easier to predict.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can I drive after using cannabis?
                </h4>

                <ul class="answer-list">

                    <li>
                        Don't drive while impaired by
                        cannabis.
                    </li>

                    <li>
                        Cannabis can slow reaction time,
                        interfere with coordination and
                        decision-making, and change
                        perception — all things you need to
                        drive safely.
                    </li>

                    <li>
                        Alcohol and cannabis together can
                        increase impairment even further.
                    </li>

                    <li>
                        There isn't one universal waiting
                        period that guarantees every person
                        is safe to drive after every cannabis
                        product.
                    </li>

                    <li>
                        Feeling less high isn't the same
                        thing as proving that you're ready to
                        drive.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Is smoking cannabis safe for your lungs?
                </h4>

                <ul class="answer-list">

                    <li>
                        Cannabis smoke isn't harmless.
                    </li>

                    <li>
                        Cannabis smoke contains many of the
                        same toxins, irritants, and
                        cancer-causing chemicals found in
                        tobacco smoke, and smoking cannabis
                        can damage lung tissue.
                    </li>

                    <li>
                        Smoking cannabis has also been
                        associated with coughing, mucus
                        production, and bronchitis symptoms.
                    </li>

                    <li>
                        Using a bong or water pipe doesn't
                        make cannabis smoke harmless.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Is vaping cannabis safer than smoking?
                </h4>

                <ul class="answer-list">

                    <li>
                        Don't assume that vaping means safe.
                    </li>

                    <li>
                        Smoking and vaping create different
                        exposures and risks, and there isn't
                        enough evidence to simply call
                        cannabis vaping safe.
                    </li>

                    <li>
                        Dry-herb vaporizers, concentrate
                        vaporizers, and oil cartridges are
                        also different products and
                        shouldn't all be treated as the same
                        thing.
                    </li>

                    <li>
                        Vape oils and concentrates can contain
                        high concentrations of THC and may
                        contain additives or contaminants.
                    </li>

                    <li>
                        Product source and quality matter.
                        Avoid cannabis vape products from
                        unknown or unregulated sources.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can cannabis affect mental health?
                </h4>

                <ul class="answer-list">

                    <li>
                        Cannabis can affect mood, anxiety,
                        perception, attention, and thinking.
                    </li>

                    <li>
                        Some people experience anxiety,
                        panic, paranoia, confusion, or other
                        unwanted mental effects while using
                        THC.
                    </li>

                    <li>
                        Cannabis use has been associated with
                        psychosis-related risks and other mental
                        health concerns. The association with
                        psychosis is stronger among people who
                        begin using cannabis at a younger age
                        and people who use it more frequently.
                    </li>

                    <li>
                        An association doesn't mean cannabis
                        explains every mental health
                        condition, but these risks shouldn't
                        be ignored.
                    </li>

                    <li>
                        If cannabis repeatedly makes your
                        mental health worse, that's worth
                        taking seriously and discussing with
                        a healthcare professional.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can cannabis affect a developing brain?
                </h4>

                <ul class="answer-list">

                    <li>
                        Yes. The brain continues developing
                        through adolescence and into young
                        adulthood.
                    </li>

                    <li>
                        Cannabis can affect attention, memory,
                        learning, decision-making,
                        coordination, and reaction time.
                    </li>

                    <li>
                        Starting cannabis use at a younger age
                        and using cannabis more frequently are
                        associated with a greater risk of
                        cannabis use disorder.
                    </li>

                    <li>
                        Scientists are still studying the
                        long-term effects of cannabis exposure
                        on developing brains.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can cannabis affect heart health?
                </h4>

                <ul class="answer-list">

                    <li>
                        Yes. Cannabis can make the heart beat
                        faster and can raise blood pressure
                        shortly after use.
                    </li>

                    <li>
                        Research is continuing into possible
                        links between cannabis use and stroke,
                        heart disease, and other cardiovascular
                        problems.
                    </li>

                    <li>
                        Smoking cannabis also exposes the body
                        to many of the same harmful substances
                        found in tobacco smoke.
                    </li>

                    <li>
                        People with heart or cardiovascular
                        conditions should discuss cannabis use
                        with a qualified healthcare
                        professional.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Is cannabis safe during pregnancy or
                    breastfeeding?
                </h4>

                <ul class="answer-list">

                    <li>
                        Health agencies recommend avoiding
                        cannabis during pregnancy and while
                        breastfeeding.
                    </li>

                    <li>
                        FDA strongly advises against using CBD,
                        THC, or marijuana in any form during
                        pregnancy or while breastfeeding.
                    </li>

                    <li>
                        THC can pass from a pregnant person to
                        the developing baby and can also be
                        present in breast milk after cannabis
                        use.
                    </li>

                    <li>
                        Pregnancy-related concerns are not
                        limited to smoking. Edibles, vaping,
                        concentrates, oils, and other cannabis
                        products can still expose the body to
                        THC or other cannabinoids.
                    </li>

                    <li>
                        If you're pregnant, breastfeeding,
                        planning a pregnancy, or currently using
                        cannabis or CBD, talk with a healthcare
                        professional about your situation.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    Can cannabis show up on a drug test?
                </h4>

                <ul class="answer-list">

                    <li>
                        Yes. THC exposure can result in a
                        positive drug test even after the
                        noticeable high has ended.
                    </li>

                    <li>
                        How long THC or its metabolites can
                        be detected varies based on the type
                        of test, frequency of use, amount
                        used, and individual differences.
                    </li>

                    <li>
                        Some products marketed as CBD or hemp
                        may contain THC, so those labels
                        don't guarantee that a drug test will
                        be negative.
                    </li>

                    <li>
                        A drug test and an impairment test
                        also aren't necessarily the same
                        thing.
                    </li>

                </ul>

            </li>

            <li>

                <h4>
                    How should cannabis be stored?
                </h4>

                <ul class="answer-list">

                    <li>
                        Keep cannabis and cannabis products
                        securely stored and out of the reach
                        and sight of children and pets.
                    </li>

                    <li>
                        Edibles deserve extra attention
                        because gummies, chocolates, baked
                        goods, and drinks can look like
                        ordinary food.
                    </li>

                    <li>
                        Keep products in clearly labeled
                        packaging when possible and avoid
                        transferring them into containers
                        that could be mistaken for normal
                        food, candy, or drinks.
                    </li>

                    <li>
                        For product quality, follow the
                        manufacturer's storage directions
                        and protect products from excessive
                        heat, light, or moisture when

                        greater concentration of THC — it
                        doesn't automatically mean the
                        product is higher quality.
                    </li>

                    <li>
                        Higher-THC products can produce more
                        intense effects and may make unwanted
                        effects easier to experience.
                    </li>

                    <li>
                        Concentrates can contain substantially
                        more THC than cannabis flower, so
                        comparing products by THC percentage
                        alone can also be misleading.
                    </li>

                    <li>
                        Potency is useful information, but it
                        isn't a quality score.
                    </li>

                </ul>

            </li>


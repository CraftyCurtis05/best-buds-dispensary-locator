                    me?
                </h4>

                <ul class="answer-list">

                    <li>
                        THC information helps describe how
                        much THC or potential THC is in a
                        product, but the way it is reported
                        depends on the type of product.
                    </li>

                    <li>
                        Flower and concentrates may use
                        percentages, while edibles,
                        tinctures, and other products often
                        use milligrams per serving,
                        container, or volume.
                    </li>

                    <li>
                        A larger number can mean more THC,
                        but it doesn't tell you everything
                        about how the product will affect
                        you.
                    </li>

                    <li>
                        Always pay attention to the unit and
                        whether the label is describing one
                        serving or the entire package.
                    </li>

                </ul>

            </li>


                    <h5>
                        What is a dab rig?
                    </h5>

                    <ul class="answer-list">

                        <li>
                            A dab rig is a device designed
                            for inhaling heated cannabis
                            concentrates.
                        </li>

                        <li>
                            Traditional rigs often use a
                            glass body and a separate heated
                            nail or banger instead of the
                            bowl normally used for flower.
                        </li>


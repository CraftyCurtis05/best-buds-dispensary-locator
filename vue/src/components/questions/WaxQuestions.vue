                            Two dabs that look similar can
                            contain very different amounts
                            of THC.
                        </li>

                        <li>
                            That's why phrases such as "one
                            dab" or "a tiny piece" don't
                            tell you an exact dose.
                        </li>

                    </ul>

                </li>

